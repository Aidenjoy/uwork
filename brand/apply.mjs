/**
 * Inject the active brand profile into every consumer: the brand plugin source,
 * the web install metadata/static icons and the desktop resource artwork.
 * Run before building (`node brand/apply.mjs`); brand/build.mjs does it automatically.
 */
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { brand, BRAND_ROOT, REPO_ROOT } from './resolve.mjs'

const assets = join(BRAND_ROOT, 'assets', brand.key)

function copyTree(from, to) {
  if (!existsSync(from)) throw new Error(`brand: missing asset directory ${from}`)
  mkdirSync(to, { recursive: true })
  cpSync(from, to, { recursive: true })
}

// 1. Brand plugin: fixed asset filenames plus a generated identity module.
const pluginClient = join(REPO_ROOT, 'packages', 'client', 'ui-brand-yundashi', 'src', 'client')
copyTree(join(assets, 'plugin'), join(pluginClient, 'assets'))
const generated = `/** Generated by brand/apply.mjs from brand/profiles/${brand.key}.json. Do not edit. */
import markUrl from './assets/mark.svg'
import markDarkUrl from './assets/mark-dark.svg'
import wordmarkUrl from './assets/wordmark.png'

/** Product identity rendered as plain text so the Chinese font follows the host theme. */
export const BRAND_NAME = ${JSON.stringify(brand.productName)}
/** Product slogan used by the welcome surface. */
export const BRAND_TAGLINE = ${JSON.stringify(brand.tagline)}
/** Accent color for the textual product name. */
export const BRAND_COLOR = ${JSON.stringify(brand.brandColor)}
/** Default home directory name under the OS home for this brand. */
export const BRAND_HOME_DIR_NAME = '${brand.homeDir}'
export { markUrl, markDarkUrl, wordmarkUrl }
`
writeFileSync(join(pluginClient, 'brand.generated.ts'), generated)

const homeDirGenerated = `/** Generated by brand/apply.mjs from brand/profiles/${brand.key}.json. Do not edit. */

/** Default home directory name under the OS home for this brand. */
export const BRAND_HOME_DIR_NAME = '${brand.homeDir}'
`
writeFileSync(join(REPO_ROOT, 'packages', 'util', 'home-paths', 'src', 'brand.generated.ts'), homeDirGenerated)
writeFileSync(join(REPO_ROOT, 'packages', 'boot', 'app-boot', 'src', 'brand.generated.ts'), homeDirGenerated)

// 2. Web install metadata and static icons.
const webPublic = join(REPO_ROOT, 'apps', 'web', 'public')
copyTree(join(assets, 'web'), webPublic)
const manifest = {
  name: brand.productName,
  short_name: brand.shortName,
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: brand.backgroundColor,
  theme_color: brand.themeColor,
  icons: [
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}
writeFileSync(join(webPublic, 'manifest.webmanifest'), `${JSON.stringify(manifest, null, 2)}\n`)
const indexPath = join(REPO_ROOT, 'apps', 'web', 'index.html')
const index = readFileSync(indexPath, 'utf8')
const titleMeta = /(<meta name="apple-mobile-web-app-title" content=")[^"]*(")/u
if (!titleMeta.test(index)) throw new Error('brand: index.html is missing the apple-mobile-web-app-title meta')
writeFileSync(indexPath, index.replace(titleMeta, `$1${brand.shortName}$2`))

// 3. Desktop resource artwork (installer icons, tray, vector source).
copyTree(join(assets, 'desktop'), join(REPO_ROOT, 'apps', 'desktop', 'resources'))

console.info(`brand: applied profile "${brand.key}" (${brand.productName})`)